# ── 7. Test _romanize_text phonetic accuracy ─────────────────────────────────

def test_romanize_text():
    """
    Test the `_romanize_text` function from translation_engine.py.
    Verifies that Indic scripts produce proper phonetic romanization
    (preserving vowels) rather than the stripped output of anyascii alone.
    """
    print("=" * 72)
    print("  7. _romanize_text phonetic accuracy")
    print("=" * 72)

    # Import the actual function from the server module
    sys.path.insert(0, os.path.join(os.path.dirname(__file__), "server"))
    from translation_engine import _romanize_text

    cases = [
        # English / Latin-script (no change)
        ("en", "Hello, how are you?", "Hello, how are you?"),
        ("fr", "Bonjour, ça va ?", "Bonjour, ça va ?"),
        ("es", "¿Cómo estás?", "¿Cómo estás?"),
        # Hindi (Devanagari → phonetic Latin via uroman)
        ("hi", "नमस्ते", "namaste"),
        ("hi", "आपका खाता शेष पाँच हज़ार रुपये है।",
               "aapakaa khaataa shess paamc hazaar rupaye hai."),
        # Tamil
        ("ta", "வணக்கம்", "vanakkam"),
        # Telugu
        ("te", "నమస్కారం", "namaskaaram"),
        # Bengali
        ("bn", "নমস্কার", "namaskaar"),
        # Gujarati
        ("gu", "નમસ્તે", "namaste"),
        # Punjabi
        ("pa", "ਨਮਸਤੇ", "namasatee"),
        # Kannada
        ("kn", "ನಮಸ್ಕಾರ", "namaskaara"),
        # Malayalam
        ("ml", "നമസ്കാരം", "namaskaaram"),
        # Marathi (Devanagari)
        ("mr", "नमस्कार", "namaskaar"),
        # Arabic (uroman preserves more vowels than anyascii)
        ("ar", "مرحبا", "mrhba"),
        # Japanese
        ("ja", "こんにちは", "konnichiha"),
        # Korean
        ("ko", "안녕하세요", "annyeonghaseyo"),
    ]

    # Scripts where anyascii fallback naturally drops vowels (consonant-only scripts)
    _CONSONANT_SCRIPTS = {"ar", "he", "dv", "ps", "ur"}

    all_ok = True
    for lang, inp, expected_prefix in cases:
        result = _romanize_text(inp, lang)
        cleaned = _lipsync_clean_text(result)
        has_content = len(cleaned) > 0

        has_vowels = bool(re.search(r'[aeiou]', cleaned))
        # Consonant-only scripts (Arabic, Hebrew) naturally lack vowels in ASCII
        expects_vowels = lang not in _CONSONANT_SCRIPTS

        status = "OK"
        if not has_content:
            status = "EMPTY"
            all_ok = False
        elif expects_vowels and not has_vowels:
            status = "NO VOWELS"
            all_ok = False

        has_vowels_str = f"vowels={'yes' if has_vowels else 'NO!'}"
        extras = has_vowels_str if expects_vowels else f"vowels={'yes' if has_vowels else 'NO!'} (expected for {lang})"
        print(f"  [{status}] {lang:4s} {inp:30s} → {result:50s} cleaned={cleaned:30s} {extras}")

    # Specific comparison: anyascii vs uroman for several scripts
    print()
    print("  Quality comparison (anyascii vs uroman):")
    from anyascii import anyascii

    comparisons = [
        ("hi", "नमस्ते"),
        ("hi", "आपका खाता शेष पाँच हज़ार रुपये है।"),
        ("ta", "வணக்கம்"),
        ("te", "నమస్కారం"),
        ("bn", "নমস্কার"),
        ("gu", "નમસ્તે"),
        ("pa", "ਨਮਸਤੇ"),
        ("ar", "مرحبا"),
        ("ja", "こんにちは"),
        ("ko", "안녕하세요"),
        ("zh", "你好"),
        ("th", "สวัสดี"),
        ("ru", "здравствуйте"),
        ("el", "γεια σας"),
    ]
    for lang, inp in comparisons:
        old_way = anyascii(inp)
        new_way = _romanize_text(inp, lang)
        old_clean = _lipsync_clean_text(old_way)
        new_clean = _lipsync_clean_text(new_way)

        better = new_clean != old_clean or len(new_clean) > len(old_clean)
        worse = len(new_clean) < len(old_clean) and new_clean != old_clean

        print(f"    [{lang}] INPUT: {inp}")
        print(f"      anyascii: {old_way:45s} → {old_clean}")
        print(f"      uroman:   {new_way:45s} → {new_clean}")
        if better:
            print(f"      ✅ BETTER")
        elif worse:
            print(f"      ❌ WORSE")
            all_ok = False
        else:
            print(f"      ➖ SAME (no regression)")
        print()

    return all_ok


