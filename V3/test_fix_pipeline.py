# ── 3. Test _get_rom proportional mapping ────────────────────────────────────

def _get_rom(i, sentences, rom_sentences):
    if not rom_sentences:
        return sentences[i]
    if len(rom_sentences) == len(sentences):
        return rom_sentences[i]
    idx = int(i * len(rom_sentences) / max(len(sentences), 1))
    return rom_sentences[min(idx, len(rom_sentences) - 1)]


def test_get_rom():
    print("=" * 72)
    print("  3. _get_rom proportional alignment")
    print("=" * 72)

    cases = [
        # Equal counts — direct mapping
        {
            "sentences": ["a.", "b?", "c!"],
            "rom_sentences": ["x.", "y?", "z!"],
            "expect": ["x.", "y?", "z!"],
        },
        # More romanized than native — distribute proportionally
        # 2 native sentences → i=0→idx=0, i=1→idx=int(1*3/2)=1
        {
            "sentences": ["a.", "b!"],
            "rom_sentences": ["x.", "y?", "z!"],
            "expect": ["x.", "y?"],
        },
        # Fewer romanized than native — distribute proportionally
        {
            "sentences": ["a.", "b?", "c!"],
            "rom_sentences": ["x.", "z!"],
            "expect": ["x.", "x.", "z!"],
        },
        # No romanized — fallback to native
        {
            "sentences": ["a.", "b!"],
            "rom_sentences": [],
            "expect": ["a.", "b!"],
        },
    ]

    all_ok = True
    for idx, case in enumerate(cases):
        got = [_get_rom(i, case["sentences"], case["rom_sentences"])
               for i in range(len(case["sentences"]))]
        match = got == case["expect"]
        status = "OK" if match else "MISMATCH"
        print(f"  [{status}] case {idx+1}: {got}")
        if not match:
            print(f"         expected: {case['expect']}")
            all_ok = False
    print()
    return all_ok


# ── 4. Test the full pipeline data flow ──────────────────────────────────────

def test_pipeline_flow():
    """
    Simulate the server pipeline for the `/ws/stt` and `/ws/tts` endpoints
    to verify the data structures are correct for the frontend lipsync.
    """
    print("=" * 72)
    print("  4. Pipeline data flow (mock — no models)")
    print("=" * 72)

    from anyascii import anyascii
    from translation_engine import _romanize_text

    # Simulate the pipeline for different languages
    scenarios = [
        # (description, user_spoke_lang, english_llm_response, native_text_mock)
        (
            "English → English",
            "en",
            "I can help you with your account balance.",
            None,  # no translation needed
        ),
        (
            "Hindi → Hindi",
            "hi",
            "Your account balance is five thousand rupees.",
            "आपका खाता शेष पाँच हज़ार रुपये है।",
        ),
        (
            "Tamil → Tamil",
            "ta",
            "Welcome to our banking service.",
            "எங்கள் வங்கிச் சேவைக்கு வரவேற்கிறோம்।",
        ),
        (
            "Arabic → Arabic",
            "ar",
            "Thank you for your patience.",
            "شكرا لك على صبرك.",
        ),
        (
            "French → French",
            "fr",
            "How can I assist you today?",
            "Comment puis-je vous aider aujourd'hui ?",
        ),
        (
            "Japanese → Japanese",
            "ja",
            "Please wait a moment.",
            "少々お待ちください。",
        ),
    ]

    all_ok = True
    for desc, lang, llm_response, native_text in scenarios:
        print(f"  ── {desc} ──")

        # Step A: Granite LLM produces English response
        eng_response = llm_response
        print(f"     LLM (English):  {eng_response!r}")

        # Step B: translate_from_english (mock the SMaLL-100 translation)
        if lang == "en":
            native = eng_response
            romanized = eng_response
        else:
            native = native_text
            romanized = _romanize_text(native, lang)

        print(f"     native_text:    {native!r}")
        print(f"     romanized_text: {romanized!r}")

        # Step C: Build the reply dict that goes to the frontend
        reply = {
            "type": "reply",
            "native_text": native,
            "romanized_text": romanized,
        }

        # Step D: Simulate frontend processing (main.js onReply handler)
        frontend_native = reply["native_text"]
        frontend_roman = reply["romanized_text"]

        # TTS speaks frontend_native, lipsync uses frontend_roman
        tts_text = frontend_native
        lipsync_text = frontend_roman

        # Step E: Simulate tts_engine sentence alignment
        native_sentences = _split_sentences(tts_text)
        rom_sentences = _split_sentences(lipsync_text) if lipsync_text else []

        alignment_match = len(native_sentences) == len(rom_sentences)
        if not alignment_match:
            print(f"     ⚠️  Sentence count mismatch: native={len(native_sentences)} romanized={len(rom_sentences)}")

        # Step F: Verify romanized_text contains Latin chars only
        has_non_latin = bool(re.search(r'[^\x00-\x7F]', lipsync_text))
        if has_non_latin and lang != "en":
            print(f"     ❌ romanized_text contains non-Latin characters!")
            all_ok = False
        elif lang != "en" and not lipsync_text.strip():
            print(f"     ❌ romanized_text is empty!")
            all_ok = False
        else:
            print(f"     ✅ Latin-only: {'yes' if not has_non_latin else 'no'}, sentences aligned: {alignment_match}")

        # Step G: Verify romanized text phonetically relates to native text
        # (at minimum, it should not be the English LLM response)
        if lang != "en":
            too_similar_to_english = lipsync_text == eng_response
            if too_similar_to_english:
                print(f"     ❌ romanized_text is still the English LLM response!")
                all_ok = False
            else:
                print(f"     ✅ romanized_text differs from English LLM response")

        print()

    return all_ok


# ── 5. Regression: lipsync can process the new romanized text ────────────────

def _lipsync_clean_text(text: str) -> str:
    """Replicates lipsync._textToVisemeEvents cleaning step."""
    return re.sub(r'[^a-zA-Z\'\s]', ' ', text).replace(r'\s+', ' ').strip()


def test_lipsync_compatibility():
    """
    Feed the romanized text through the frontend lipsync cleaning step
    to verify it produces usable visemes (non-empty after cleaning).
    """
    print("=" * 72)
    print("  5. Lipsync compatibility (text cleaning)")
    print("=" * 72)

    from translation_engine import _romanize_text

    # (name, lang_code, native_text)
    samples = [
        ("Hindi",    "hi", "आपका खाता शेष पाँच हज़ार रुपये है।"),
        ("Tamil",    "ta", "எங்கள் வங்கிச் சேவைக்கு வரவேற்கிறோம்।"),
        ("Arabic",   "ar", "شكرا لك على صبرك."),
        ("French",   "fr", "Comment puis-je vous aider ?"),
        ("Japanese", "ja", "少々お待ちください。"),
        ("Korean",   "ko", "잠시만 기다려주세요."),
    ]

    all_ok = True
    for name, lang_code, native in samples:
        romanized = _romanize_text(native, lang_code)
        cleaned = _lipsync_clean_text(romanized)
        has_content = len(cleaned) > 0
        print(f"  [{ 'OK' if has_content else 'FAIL' }] {name:10s} cleaned({len(cleaned):3d} chars): {cleaned[:60]!r}")
        if not has_content:
            all_ok = False
    return all_ok


